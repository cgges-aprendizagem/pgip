import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const packageJsonPath = require.resolve('lucide-static/package.json');
const packageDir = dirname(packageJsonPath);
const packageJson = JSON.parse(await readFile(packageJsonPath, 'utf8'));
const nodes = JSON.parse(await readFile(resolve(packageDir, 'icon-nodes.json'), 'utf8'));
const tags = JSON.parse(await readFile(resolve(packageDir, 'tags.json'), 'utf8'));
const license = await readFile(resolve(packageDir, 'LICENSE'), 'utf8');

function escapeAttribute(value) {
  return String(value)
    .replaceAll('&', '&amp;')
    .replaceAll('"', '&quot;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;');
}

function serializeNode([tag, attributes]) {
  const attrs = Object.entries(attributes)
    .map(([key, value]) => `${key}="${escapeAttribute(value)}"`)
    .join(' ');
  return `<${tag}${attrs ? ` ${attrs}` : ''}/>`;
}

const iconNames = Object.keys(nodes).sort();
const icons = Object.fromEntries(iconNames.map((name) => [
  name,
  nodes[name].map(serializeNode).join(''),
]));
const searchTerms = Object.fromEntries(iconNames.map((name) => [name, tags[name] || []]));

const output = `/* This file is generated by scripts/generate-lucide-catalog.mjs.
 * Source: lucide-static ${packageJson.version} (ISC; some Feather icons are MIT).
 * Do not edit manually.
 */
export const LUCIDE_VERSION = ${JSON.stringify(packageJson.version)};
export const LUCIDE_LICENSE_NOTICE = ${JSON.stringify(license)};
export const LUCIDE_ICONS: Record<string, string> = ${JSON.stringify(icons)};
export const LUCIDE_SEARCH_TERMS: Record<string, string[]> = ${JSON.stringify(searchTerms)};
`;

const outputPath = resolve(root, 'src/generated/lucideCatalog.ts');
await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, output);
console.log(`Generated ${iconNames.length} Lucide icons at ${outputPath}`);
